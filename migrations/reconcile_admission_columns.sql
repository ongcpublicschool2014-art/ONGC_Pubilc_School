-- Reconcile the live public.admission table with complete_setup.sql.
-- The live table drifted (missing yr_id / stu_id / allocation + extended student
-- columns), so process_student_import's admission mirror and the normal
-- admission->allocate flow can't write it. Adds every missing column (ADD COLUMN
-- IF NOT EXISTS), all NULLABLE so existing admission rows are unaffected.
-- Idempotent — re-runnable; already-present columns are skipped.

