-- =====================================================================
-- Read only. Will the NEXT institution's schema be built correctly?
--
-- A new tenant is created entirely by public.create_institution_schema, so
-- whatever that function contains on THIS database is what the next
-- institution gets. If it is older than the schema the existing tenants have
-- grown into, the new institution is born stale -- missing columns, missing
-- constraints, missing triggers -- and the failures look like application bugs
-- months later.
--
-- This compares the deployed builder against the features a tenant needs
-- today. Run it on LIVE before creating the second institution.
--
-- Every row must say 'yes'.
-- =====================================================================
WITH b AS (
  SELECT prosrc AS src
    FROM pg_proc
   WHERE proname = 'create_institution_schema'
     AND pronamespace = 'public'::regnamespace
)
SELECT * FROM (
  SELECT 1 AS ord, 'builder exists' AS feature,
         CASE WHEN EXISTS (SELECT 1 FROM b) THEN 'yes' ELSE 'NO' END AS ok,
         'public.create_institution_schema' AS detail

  -- Every PK in a tenant schema is generated by a BEFORE INSERT trigger. A
  -- schema built without them fails EVERY insert with 23502, which the app
  -- shows as the generic red "Payment failed". This has already been
  -- misdiagnosed twice (payment.pay_id, paymentdetails.pyd_id).
  UNION ALL SELECT 2, 'creates PK triggers',
         CASE WHEN (SELECT src FROM b) LIKE '%CREATE TRIGGER%' THEN 'yes' ELSE 'NO' END,
         'set_pay_id / set_pyd_id / set_dem_id and friends'

  UNION ALL SELECT 3, 'payment.ban_id (which account the money is in)',
         CASE WHEN (SELECT src FROM b) LIKE '%ban_id%' THEN 'yes' ELSE 'NO' END,
         'needed by reporting and by Paytm recovery'

  UNION ALL SELECT 4, 'bank.paytm_mid (per-account merchant)',
         CASE WHEN (SELECT src FROM b) LIKE '%paytm_mid%' THEN 'yes' ELSE 'NO' END,
         'needed before fee-group routing can work'

  UNION ALL SELECT 5, 'advance type M (mess) allowed',
         -- the constraint lives inside an EXECUTE format() string, so its
         -- quotes are DOUBLED in prosrc. Match on the constraint name and the
         -- letter instead of trying to reproduce the quoting.
         CASE WHEN (SELECT src FROM b) ~ 'chk_advance_advtype[^;]*M' THEN 'yes' ELSE 'NO' END,
         'otherwise a mess advance cannot be saved'

  UNION ALL SELECT 6, 'misc_collection + detail',
         CASE WHEN (SELECT src FROM b) LIKE '%misc_collection_detail%' THEN 'yes' ELSE 'NO' END,
         'miscellaneous receipts'

  UNION ALL SELECT 7, 'advance_collection + detail',
         CASE WHEN (SELECT src FROM b) LIKE '%advance_detail%' THEN 'yes' ELSE 'NO' END,
         'advances and their fee-type breakdown'

  UNION ALL SELECT 8, 'advadjustment',
         CASE WHEN (SELECT src FROM b) LIKE '%advadjustment%' THEN 'yes' ELSE 'NO' END,
         'settling an advance against a demand'

  UNION ALL SELECT 9, 'fee_refund + details',
         CASE WHEN (SELECT src FROM b) LIKE '%fee_refunddetails%' THEN 'yes' ELSE 'NO' END,
         'refunds'

  UNION ALL SELECT 10, 'sequence carries fg_id (receipt series per fee group)',
         CASE WHEN (SELECT src FROM b) LIKE '%sequence%fg_id%' THEN 'yes' ELSE 'NO' END,
         'receipt numbering'

  -- How the existing tenants actually look, for comparison. A new schema
  -- should come out with the same table and trigger counts.
  UNION ALL
  SELECT 11, 'existing tenant: ' || public.get_institution_schema(i.ins_id),
         (SELECT count(*)::text FROM information_schema.tables t
           WHERE t.table_schema = public.get_institution_schema(i.ins_id))
         || ' tables',
         (SELECT count(*)::text FROM pg_trigger tg
            JOIN pg_class c ON c.oid = tg.tgrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
           WHERE n.nspname = public.get_institution_schema(i.ins_id)
             AND NOT tg.tgisinternal) || ' triggers'
    FROM public.institution i WHERE i.activestatus = 1
) r ORDER BY r.ord, r.feature;
