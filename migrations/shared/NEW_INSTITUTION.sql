-- =====================================================================
-- Add a new institution and build its schema.
--
-- EduCore360 is multi-tenant: every institution gets its OWN schema holding
-- its students, fees, payments and receipts. public.get_institution_schema()
-- maps ins_id -> schema name, and every money RPC resolves the schema that way,
-- so nothing in the application needs changing to add a tenant.
--
-- The schema name is  <inshortname><year label without the dash>
-- e.g. inshortname 'kcet' + '2026-2027'  ->  kcet20262027
-- That is the same rule the Dashboard uses when it creates a new academic year
-- (dashboard_screen.dart), so keep to it or the two will disagree.
--
-- WHAT THIS DOES NOT DO: master data. A new schema has empty courses, classes,
-- fee groups, fee types, banks and sequences. Those are entered or imported in
-- the app afterwards, and in a required order -- master data and the admission
-- master must exist before students can be imported.
--
-- EDIT THE VALUES IN STEP 1, then run the whole file.
-- =====================================================================

-- ---------------------------------------------------------------------
-- STEP 1 -- the institution row.
--
-- ins_id has NO default, so it is supplied explicitly. Take the next free one.
-- inshortname drives the schema name, so keep it short, lowercase and stable --
-- renaming it later does NOT rename the schema.
-- ---------------------------------------------------------------------
INSERT INTO public.institution (
  ins_id, insname, inscode, inshortname,
  insautusername, insdesignation, insmobno, insmail,
  it_id, insrecognised, insaddress1, inspincode,
  insipaddress, inssername, insserurl,
  insapproved, activestatus, updatedby
) VALUES (
  2,                                   -- <<< ins_id: next free number
  'Second College Name Here',          -- <<< insname
  '0000',                              -- <<< inscode
  'scn',                               -- <<< inshortname -> schema prefix
  'admin', 'Principal', '0000000000', 'admin@example.com',
  1, 'Y', 'Address line 1', '000000',
  '-', '-', '-',
  1, 1, 'ADMIN'
)
ON CONFLICT (ins_id) DO NOTHING;

-- ---------------------------------------------------------------------
-- STEP 2 -- build that institution's schema for its first academic year.
--
-- Creates every table, sequence and BEFORE INSERT trigger the tenant needs.
-- The triggers matter: every primary key in a tenant schema is generated by
-- one, so a schema without them fails every insert with
--   23502 null value in column "<pk>" violates not-null constraint
-- which the app shows as the generic red "Payment failed".
-- ---------------------------------------------------------------------
SELECT public.create_institution_schema(
  'scn20262027',        -- <<< inshortname || year label without the dash
  2,                    -- <<< the ins_id from step 1
  '2026-2027',          -- <<< year label
  DATE '2026-06-01',    -- <<< year start
  DATE '2027-05-31'     -- <<< year end
);

-- ---------------------------------------------------------------------
-- STEP 3 -- Paytm merchant, if this institution collects online.
--
-- resolvePaytmRouting REFUSES a payment it cannot route rather than falling
-- back to another institution's merchant -- that fallback is how money
-- silently reached the wrong account after a rebuild. So a tenant with no row
-- here simply cannot take online payments, which is the safe failure.
--
-- The merchant's KEY is not stored here: it goes in the PAYTM_MERCHANTS edge
-- secret, as {"<mid>":"<key>", ...}. A merchant with no key entry is rejected
-- server-side rather than silently mis-settled.
-- ---------------------------------------------------------------------
-- INSERT INTO public.paytm_configuration
--        (institution_id, merchant_id, website, industry_type, channel_id, is_active)
-- VALUES (2, '<merchant id>', 'DEFAULT', 'Retail', 'WEB', true);

-- ---------------------------------------------------------------------
-- VERIFY
-- ---------------------------------------------------------------------
SELECT i.ins_id, i.insname, i.inshortname,
       public.get_institution_schema(i.ins_id) AS schema_name,
       (SELECT count(*) FROM information_schema.tables t
         WHERE t.table_schema = public.get_institution_schema(i.ins_id)) AS tables,
       (SELECT count(*) FROM pg_trigger tg
          JOIN pg_class c ON c.oid = tg.tgrelid
          JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE n.nspname = public.get_institution_schema(i.ins_id)
           AND NOT tg.tgisinternal) AS triggers,
       (SELECT count(*) FROM public.paytm_configuration p
         WHERE p.institution_id = i.ins_id AND p.is_active) AS paytm_merchants
  FROM public.institution i
 WHERE i.activestatus = 1
 ORDER BY i.ins_id;

-- A healthy new tenant shows the same table and trigger counts as the existing
-- one. Zero triggers means the schema was built by something other than
-- create_institution_schema (a restore, for instance) and every insert will
-- fail -- see tools/restore_test_repair.sql.

