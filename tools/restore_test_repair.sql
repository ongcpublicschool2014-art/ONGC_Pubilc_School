-- RESTORE REPAIR -- run this on TEST after every live -> TEST restore.
--
-- pg_restore brings the tables, the data and the sequences but leaves several
-- things behind. Each one has already cost a wrong diagnosis -- and the last
-- one is the opposite problem, where the restore leaves TEST MORE open than
-- live rather than broken, so nothing misbehaves and nobody notices:
--
--   1. SCHEMA GRANTS   login still works (create_app_session lives in public)
--                      but every data screen fails with "permission denied for
--                      schema kcet20262027". Looks like a stale PostgREST
--                      cache; reloading the cache changes nothing.
--   2. COLUMN DEFAULTS integer PKs lose their default while the sequence
--                      survives. Read once as "Paytm is not working"
--                      (payment.pay_id).
--   3. FOREIGN KEYS    ALL of them. Beyond referential integrity, PostgREST
--                      resolves an EMBEDDED select from the foreign key, so
--                      feedemand?select=*,feetype(*,feegroup(*)) stops working
--                      and the parent app silently falls back to a plain
--                      select -- every fee then reports no fee group, and the
--                      cart's "one fee group per cart" guard passes without
--                      firing. Two fee groups in one cart, 2026-10-01.
--   4. TRIGGERS        ALL of them, and every primary key in this schema is
--                      generated by a BEFORE INSERT trigger. Inserts fail with
--                      23502 null value in column "<pk>", which the app shows
--                      as the red "Payment failed. Something went wrong."
--                      Read once as a broken fee collection
--                      (paymentdetails.pyd_id), 2026-10-01.
--   5. THE TEST MARKER  dropped with everything else, so the one thing that
--                      can tell TEST from live disappears exactly when a
--                      restore has just made the two databases identical.
--   6. PUBLIC HARDENING  -- the dangerous one, because nothing breaks.
--                      Restoring RECREATES public.pending_collection and
--                      public.webhook_refusal, so Supabase's DEFAULT
--                      PRIVILEGES hand anon everything at creation, and the
--                      original REVOKE is never replayed -- a dump records the
--                      grants that exist, never the ones deliberately absent.
--                      After 2026-10-05 anon could write both recovery tables
--                      and execute all ten recovery functions, including the
--                      three meant for service_role alone. The app worked
--                      perfectly throughout: the app was never what the
--                      revokes were keeping out.
--
-- Parts 2 and 3 are detected and repaired generically rather than by name, so
-- a column or trigger added later is covered without editing this file.
--
-- NEVER run this against live. Live is not restored and needs none of it.
-- Safe to re-run.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Schema grants, then live's own hardening on top. Without the REVOKE,
--    TEST is MORE permissive than production and hides the class of bug the
--    hardening exists to catch (anon must be SELECT-only on these four).
-- ---------------------------------------------------------------------
GRANT USAGE ON SCHEMA kcet20262027 TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES    IN SCHEMA kcet20262027 TO authenticated, service_role, anon;
GRANT ALL ON ALL SEQUENCES IN SCHEMA kcet20262027 TO authenticated, service_role, anon;
REVOKE INSERT, UPDATE, DELETE ON
    kcet20262027.payment, kcet20262027.paymentdetails,
    kcet20262027.feedemand, kcet20262027.advance_collection
  FROM anon;

-- ---------------------------------------------------------------------
-- 2. Column defaults.
-- ---------------------------------------------------------------------
DO $repair$
DECLARE r record; v_max bigint; n int := 0;
BEGIN
  FOR r IN
    SELECT c.table_name AS tbl, c.column_name AS col,
           c.table_name || '_' || c.column_name || '_seq' AS seq
      FROM information_schema.columns c
     WHERE c.table_schema = 'kcet20262027'
       AND c.is_nullable = 'NO'
       AND c.column_default IS NULL
       AND c.is_identity = 'NO'
       AND c.data_type IN ('bigint', 'integer', 'smallint')
       AND EXISTS (SELECT 1 FROM information_schema.sequences s
                    WHERE s.sequence_schema = 'kcet20262027'
                      AND s.sequence_name = c.table_name || '_' || c.column_name || '_seq')
     ORDER BY c.table_name
  LOOP
    -- Park the sequence above the highest id already in the table, or the first
    -- insert collides with an existing row.
    EXECUTE format('SELECT COALESCE(MAX(%I), 0) FROM kcet20262027.%I', r.col, r.tbl)
      INTO v_max;
    EXECUTE format('SELECT setval(''kcet20262027.%I'', GREATEST(%s, 1), %L)',
                   r.seq, v_max, v_max > 0);
    EXECUTE format('ALTER TABLE kcet20262027.%I ALTER COLUMN %I SET DEFAULT nextval(''kcet20262027.%I'')',
                   r.tbl, r.col, r.seq);
    -- Tie them together so the sequence is dropped with the table and future
    -- dumps carry the ownership.
    EXECUTE format('ALTER SEQUENCE kcet20262027.%I OWNED BY kcet20262027.%I.%I',
                   r.seq, r.tbl, r.col);
    RAISE NOTICE 'restored default: %.% -> % (next %)', r.tbl, r.col, r.seq, v_max + 1;
    n := n + 1;
  END LOOP;

  IF n = 0 THEN
    RAISE NOTICE 'nothing to repair -- every column already has its default';
  ELSE
    RAISE NOTICE '% column default(s) restored', n;
  END IF;
END $repair$;

