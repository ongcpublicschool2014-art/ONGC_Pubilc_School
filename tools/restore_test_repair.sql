-- =====================================================================
-- TEST MARKER -- so a query can say which database it is running on.
--
-- Seven times in one day a live-intended statement was run against TEST, or a
-- TEST result was read as live. The breadcrumb is the only distinguishing
-- feature (`TBS School FREE` vs `PRO KRISHNASAMY_INSTITUTION`), both projects
-- are named KCET, both carry a `main PRODUCTION` chip, and it crops out of a
-- screenshot. Nothing in the DATA distinguishes them -- TEST is a restore of
-- live, so every value on live also exists on TEST, and row counts drift apart
-- in whichever direction TEST happens to be used.
--
-- So plant a marker that only ever exists here. A restore wipes it, which is
-- exactly when this script runs again and puts it back.
--
-- Use it at the top of anything environment-sensitive:
--     SELECT public.db_env();     -- 'TEST' or 'LIVE'
-- =====================================================================
-- The marker is the table LIVE_REMAINING_2026_10_01.sql part 1 already tests
-- for (`to_regclass('public._this_is_the_test_project')`). Reuse it rather than
-- introducing a second convention -- a restore drops it, which is exactly when
-- this script runs again and recreates it.
CREATE TABLE IF NOT EXISTS public._this_is_the_test_project (
  note text PRIMARY KEY,
  marked_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public._this_is_the_test_project (note)
VALUES ('TEST project. Never run live-intended SQL here, and never read a '
        'result from here as if it were live.')
ON CONFLICT (note) DO NOTHING;

-- Deliberately NOT marker-present = TEST / marker-absent = LIVE by assumption:
-- a restore that never got repaired would then impersonate live, which is the
-- dangerous direction. Live is only ever reported when the marker is absent AND
-- this function exists to say so -- and this function is only created here, on
-- TEST. On live it does not exist, so the call errors loudly instead of lying.
CREATE OR REPLACE FUNCTION public.db_env() RETURNS text
LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN to_regclass('public._this_is_the_test_project') IS NOT NULL
              THEN 'TEST' ELSE 'UNMARKED - do not assume live' END;
$$;
GRANT EXECUTE ON FUNCTION public.db_env() TO anon, authenticated;

-- =====================================================================
-- 6. THE PUBLIC SCHEMA'S OWN HARDENING
--
-- pg_restore does not merely STRIP privileges here, it WIDENS them -- the
-- direction nobody thinks to check. Restoring RECREATES
-- public.pending_collection and public.webhook_refusal; Supabase's DEFAULT
-- PRIVILEGES then grant anon everything the instant a table is created in
-- `public`; and the original REVOKE is never replayed, because a dump records
-- the grants that EXIST and has no way to record the ones deliberately absent.
-- The same happens to function EXECUTE.
--
-- Measured on TEST after the 05-10-2026 restore: anon could INSERT into both
-- recovery tables and EXECUTE all ten recovery functions, including the three
-- meant for service_role alone. Nothing looked wrong -- the app behaved
-- normally, because the app was never the thing being kept out.
--
-- So TEST silently becomes a weaker security model than live, which makes it
-- useless for checking access control unless this runs.
--
-- NOT a blanket revoke. list_pending_collections is deliberately callable by
-- anon: the Transactions screen reads pending misc/advance through it,
-- precisely BECAUSE the table itself is closed. Revoking that as well is what
-- broke the screen once before -- the REVOKE took SELECT with it, the catch
-- swallowed the error, and the screen showed nothing while claiming nothing.
--
-- Signatures come from migrations/shared/ -- the designed state -- never from a
-- restored database. A function missing here is skipped rather than fatal: an
-- older dump may predate it.
-- =====================================================================
DO $harden$
DECLARE s text; n int := 0; skipped int := 0;
BEGIN
  FOREACH s IN ARRAY ARRAY[
    'REVOKE ALL ON public.pending_collection FROM PUBLIC, anon, authenticated',
    'REVOKE ALL ON public.webhook_refusal FROM PUBLIC, anon, authenticated',
    'REVOKE ALL ON FUNCTION public.webhook_record_refusal(text, text, integer, bigint, numeric) FROM PUBLIC, anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.webhook_record_refusal(text, text, integer, bigint, numeric) TO service_role',
    'REVOKE ALL ON FUNCTION public.resolve_webhook_refusal(text, text, text) FROM PUBLIC, anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.resolve_webhook_refusal(text, text, text) TO service_role',
    'REVOKE ALL ON FUNCTION public.webhook_complete_collection(text, text) FROM PUBLIC, anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.webhook_complete_collection(text, text) TO service_role',
    'REVOKE ALL ON FUNCTION public._save_advance_collection(integer, jsonb, jsonb) FROM PUBLIC, anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public._save_advance_collection(integer, jsonb, jsonb) TO service_role',
    'REVOKE ALL ON FUNCTION public.list_pending_collections(integer, date, date) FROM PUBLIC',
    'GRANT EXECUTE ON FUNCTION public.list_pending_collections(integer, date, date) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.record_pending_collection(text, integer, text, numeric, jsonb, jsonb, text) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.record_pending_collection(text, integer, text, numeric, jsonb, jsonb, text, integer) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.claim_pending_collection(text, text) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.settle_pending_collection(text, text, text) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.open_pending_collections(integer) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.pending_collection_payload(text) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.backdate_recovered_collection(text) TO anon, authenticated',
    'GRANT EXECUTE ON FUNCTION public.backdate_recovered_payment(integer, text, timestamp) TO anon, authenticated'
  ] LOOP
    BEGIN
      EXECUTE s;
      n := n + 1;
    EXCEPTION WHEN undefined_function OR undefined_table OR undefined_object THEN
      skipped := skipped + 1;
    END;
  END LOOP;
  RAISE NOTICE 'public hardening: % applied, % skipped (not in this dump)', n, skipped;
END $harden$;



-- =====================================================================
-- 7. THE TIMEZONE LEDGER, WHICH OUTLIVES THE DATA IT DESCRIBES
--
-- public.tz_migration records that the IST shift has been applied, so the
-- migration can be re-run safely. A restore breaks that promise: the table is
-- NOT in a live dump taken before live was migrated, so --clean has nothing to
-- drop it with, and the row survives while the DATA underneath it is replaced
-- with live's. The ledger then says "already shifted" about rows that never
-- were, PART 2b of the release skips, and TEST is left holding UTC data in a
-- session set to Asia/Kolkata -- stamping new rows IST against UTC history.
--
-- It cannot simply be cleared: once live itself is migrated, the dump WILL
-- contain the table and its row will be correct. So decide from the DATA.
--
-- The counter's own CASH receipts are the tell, across thousands of rows: a
-- college counter works ~09:00-17:00, so a busiest hour before 07:00 means the
-- clock is UTC and the shift has NOT been applied to what is sitting here now.
-- =====================================================================
DO $tzl$
DECLARE v_peak int; v_rows int;
BEGIN
  IF to_regclass('public.tz_migration') IS NULL THEN RETURN; END IF;

  SELECT extract(hour from paydate)::int INTO v_peak
    FROM kcet20262027.payment
   WHERE paynumber IS NOT NULL AND activestatus = 1
     AND lower(COALESCE(paymethod, '')) = 'cash'
     AND paydate::time <> '00:00:00'
   GROUP BY 1 ORDER BY count(*) DESC LIMIT 1;

  IF v_peak IS NULL THEN
    RAISE NOTICE 'timezone ledger: no cash receipts to judge by -- left alone';
    RETURN;
  END IF;

  IF v_peak < 7 THEN
    DELETE FROM public.tz_migration;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    RAISE NOTICE 'timezone ledger: busiest cash hour is %:00, so this data is '
                 'UTC and has NOT been shifted -- cleared % stale row(s). RUN '
                 'migrations/shared/RELEASE_LIVE_2026_10_05_ALL.sql NEXT.',
                 v_peak, v_rows;
  ELSE
    RAISE NOTICE 'timezone ledger: busiest cash hour is %:00, so this data is '
                 'already IST -- ledger left as it is.', v_peak;
  END IF;
END $tzl$;


NOTIFY pgrst, 'reload schema';


-- ---------------------------------------------------------------------
-- VERIFY the hardening. All three must read ok.
-- ---------------------------------------------------------------------
SELECT 'anon cannot write the recovery tables' AS check,
       CASE WHEN has_table_privilege('anon','public.pending_collection','INSERT')
              OR has_table_privilege('anon','public.webhook_refusal','INSERT')
            THEN 'FAILED - anon can write' ELSE 'ok' END AS state
UNION ALL
SELECT 'webhook-only functions are service_role only',
       CASE WHEN EXISTS (
              SELECT 1 FROM pg_proc p JOIN pg_namespace ns ON ns.oid = p.pronamespace
               WHERE ns.nspname = 'public'
                 AND p.proname IN ('webhook_record_refusal','webhook_complete_collection',
                                   '_save_advance_collection','resolve_webhook_refusal')
                 AND has_function_privilege('anon', p.oid, 'EXECUTE'))
            THEN 'FAILED - anon can execute' ELSE 'ok' END
UNION ALL
SELECT 'the Transactions screen can still read pending collections',
       CASE WHEN EXISTS (
              SELECT 1 FROM pg_proc p JOIN pg_namespace ns ON ns.oid = p.pronamespace
               WHERE ns.nspname = 'public' AND p.proname = 'list_pending_collections'
                 AND has_function_privilege('anon', p.oid, 'EXECUTE'))
            THEN 'ok' ELSE 'FAILED - screen would show nothing' END
 ORDER BY 1;
